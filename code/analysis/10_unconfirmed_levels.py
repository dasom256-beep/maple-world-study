files = glob.glob(U + 'maple_main_v4/records_*.csv') + glob.glob(U + 'maple_main_v5/records_2026-10-28_*.csv')
d, win, cl = load(files)
w = win[win.world.isin(REG)].copy()
wf = w.world_first_seen.fillna('').replace(ALIAS)
w['cat'] = np.select([w.confirmed, wf == '', wf.str.startswith('버닝'), w.date_first_seen.fillna('9') >= '2024-02-22'], ['conf', 'nohist', 'burning', 'late'], 'other')
w['grp'] = np.where(w.world.isin(TREAT), 'treat', np.where(w.world.isin(LARGE), 'large', 'small'))
w['per'] = np.where(w.dc < L1, 'pre', np.where(w.dc == L1, 'lift', 'post'))
print(pd.crosstab([w.grp, w.per], w.cat, margins=False))
w['lv'] = w.level_band_now.fillna('').str.split('-').str[0].replace('', np.nan).astype(float)
w['lvb'] = pd.cut(w.lv, [0, 200, 210, 260, 400], right=False, labels=['<200', '200-209', '210-259', '260+'])
for c in ['nohist', 'late', 'conf']:
    t = pd.crosstab([w[w.cat == c].grp, w[w.cat == c].per], w[w.cat == c].lvb, normalize='index').round(2)
    print('==', c); print(t)
print('median level by cat/grp/per'); print(w.groupby(['cat', 'grp', 'per']).lv.median().unstack())
